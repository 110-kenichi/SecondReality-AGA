a = bytearray(open(sys.argv[1], 'rb').read())
b = open(sys.argv[2], 'rb').read()


def patinfo(d):
    ordnum, insnum, patnum = struct.unpack_from('<HHH', d, 0x20)
    pat_pp = list(struct.unpack_from('<%dH' % patnum, d, 0x60 + ordnum + 2 * insnum))
    return patnum, pat_pp


patnum, pp = patinfo(a)
_, pp2 = patinfo(b)

for p in range(patnum):
    off = pp[p] * 16
    if off == 0:
        continue
    ln = struct.unpack_from('<H', a, off)[0]
    for i in range(ln):
        a[off + i] ^= KEY[i & 0xFF]

diffs = []
i = 0
n = min(len(a), len(b))
while i < n:
    if a[i] != b[i]:
        s = i
        while i < n and a[i] != b[i]:
            i += 1
        diffs.append((s, i))
    else:
        i += 1
total = sum(e - s for s, e in diffs)
print(f"decoded original vs standard: {len(diffs)} diff regions, {total} differing bytes")
for s, e in diffs[:20]:
    print(f"  0x{s:06X}-0x{e:06X} ({e - s} bytes)")
    da = a[s:min(e, s + 24)]
    st = b[s:min(e, s + 24)]
    print(f"    dec: {' '.join(f'{x:02X}' for x in da)}")
    print(f"    std: {' '.join(f'{x:02X}' for x in st)}")

if '--write' in sys.argv:
    out = sys.argv[sys.argv.index('--write') + 1]
    open(out, 'wb').write(bytes(a))
    print(f"wrote {out}")
