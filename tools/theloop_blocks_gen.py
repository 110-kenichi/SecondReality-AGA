"""Emit src/m2/parts/theloop_blocks.c (the reference block table) from tools/kblocks.h."""
import re
from pathlib import Path

src = Path('tools/kblocks.h').read_text(encoding='utf-8')
rows = re.findall(r'\{\s*(\d+)\s*,\s*(-?\d+)\s*,\s*(-?\d+)\s*,\s*(0x[0-9A-Fa-f]+|\d+)U\s*\}', src)
assert len(rows) == 128, len(rows)

out = ['/* generated by tools/theloop_blocks_gen.py from tools/kblocks.h -- do not edit */',
       '#include "../framework/framework.h"',
       '#include "theloop_blocks.h"',
       '',
       'const TlBlock tl_blocks[128] = {']
for mode, bx, dx, inc in rows:
    out.append('    { %su, %s, %s, %s },' % (inc, bx, dx, mode))
out.append('};')
Path('src/m2/parts/theloop_blocks.c').write_text('\n'.join(out) + '\n', encoding='utf-8', newline='\n')
print('wrote theloop_blocks.c (%d blocks)' % len(rows))
